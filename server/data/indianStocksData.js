/**
 * Helper to generate realistic historical price curve for standard chart filters:
 * 1D, 1W, 1M, 3M, 6M, 1Y
 */
const generateChartData = (currentPrice, changePercent) => {
  const isUp = changePercent >= 0;
  const factor = isUp ? 1 : -1;

  // 1D: Intraday 15-45 min intervals from 09:15 to 15:30
  const openPrice = +(currentPrice * (1 - changePercent / 100)).toFixed(2);
  const p1 = +(openPrice + (currentPrice - openPrice) * 0.25 + (Math.random() * 4 - 2)).toFixed(2);
  const p2 = +(openPrice + (currentPrice - openPrice) * 0.45 + (Math.random() * 6 - 3)).toFixed(2);
  const p3 = +(openPrice + (currentPrice - openPrice) * 0.60 + (Math.random() * 4 - 2)).toFixed(2);
  const p4 = +(openPrice + (currentPrice - openPrice) * 0.80 + (Math.random() * 5 - 2)).toFixed(2);
  const p5 = +(openPrice + (currentPrice - openPrice) * 0.92 + (Math.random() * 3 - 1)).toFixed(2);

  const oneDay = [
    { time: '09:15', price: openPrice, volume: 145000 },
    { time: '10:15', price: p1, volume: 280000 },
    { time: '11:30', price: p2, volume: 195000 },
    { time: '12:45', price: p3, volume: 160000 },
    { time: '14:00', price: p4, volume: 240000 },
    { time: '15:00', price: p5, volume: 320000 },
    { time: '15:30', price: currentPrice, volume: 410000 },
  ];

  // 1W: Mon - Fri
  const w1 = +(currentPrice * (1 - 0.025 * factor)).toFixed(2);
  const w2 = +(currentPrice * (1 - 0.018 * factor)).toFixed(2);
  const w3 = +(currentPrice * (1 - 0.012 * factor)).toFixed(2);
  const w4 = +(currentPrice * (1 - 0.005 * factor)).toFixed(2);
  const oneWeek = [
    { time: 'Mon', price: w1, volume: 2100000 },
    { time: 'Tue', price: w2, volume: 2450000 },
    { time: 'Wed', price: w3, volume: 1980000 },
    { time: 'Thu', price: w4, volume: 2700000 },
    { time: 'Fri', price: currentPrice, volume: 3100000 },
  ];

  // 1M: 4 Weeks
  const m1 = +(currentPrice * (1 - 0.05 * factor)).toFixed(2);
  const m2 = +(currentPrice * (1 - 0.035 * factor)).toFixed(2);
  const m3 = +(currentPrice * (1 - 0.015 * factor)).toFixed(2);
  const oneMonth = [
    { time: 'Week 1', price: m1, volume: 11500000 },
    { time: 'Week 2', price: m2, volume: 12400000 },
    { time: 'Week 3', price: m3, volume: 10800000 },
    { time: 'Week 4', price: currentPrice, volume: 13200000 },
  ];

  // 3M: Bi-weekly for 3 months
  const threeMonths = [
    { time: 'Month 1 W1', price: +(currentPrice * (1 - 0.08 * factor)).toFixed(2) },
    { time: 'Month 1 W3', price: +(currentPrice * (1 - 0.065 * factor)).toFixed(2) },
    { time: 'Month 2 W1', price: +(currentPrice * (1 - 0.05 * factor)).toFixed(2) },
    { time: 'Month 2 W3', price: +(currentPrice * (1 - 0.03 * factor)).toFixed(2) },
    { time: 'Month 3 W1', price: +(currentPrice * (1 - 0.015 * factor)).toFixed(2) },
    { time: 'Current', price: currentPrice },
  ];

  // 6M: 6 Months
  const sixMonths = [
    { time: '5M Ago', price: +(currentPrice * (1 - 0.14 * factor)).toFixed(2) },
    { time: '4M Ago', price: +(currentPrice * (1 - 0.11 * factor)).toFixed(2) },
    { time: '3M Ago', price: +(currentPrice * (1 - 0.08 * factor)).toFixed(2) },
    { time: '2M Ago', price: +(currentPrice * (1 - 0.05 * factor)).toFixed(2) },
    { time: '1M Ago', price: +(currentPrice * (1 - 0.02 * factor)).toFixed(2) },
    { time: 'Current', price: currentPrice },
  ];

  // 1Y: 4 Quarters / 12 Months
  const oneYear = [
    { time: 'Q1', price: +(currentPrice * (1 - 0.22 * factor)).toFixed(2) },
    { time: 'Q2', price: +(currentPrice * (1 - 0.15 * factor)).toFixed(2) },
    { time: 'Q3', price: +(currentPrice * (1 - 0.08 * factor)).toFixed(2) },
    { time: 'Q4', price: currentPrice },
  ];

  return {
    '1D': oneDay,
    '1W': oneWeek,
    '1M': oneMonth,
    '3M': threeMonths,
    '6M': sixMonths,
    '1Y': oneYear,
  };
};

/**
 * Generate simulated market depth (Top 5 bid and ask levels)
 */
const generateMarketDepth = (price) => {
  const bids = [
    { orders: 42, quantity: 1850, price: +(price - 0.05).toFixed(2) },
    { orders: 86, quantity: 4200, price: +(price - 0.15).toFixed(2) },
    { orders: 120, quantity: 6850, price: +(price - 0.30).toFixed(2) },
    { orders: 64, quantity: 3100, price: +(price - 0.50).toFixed(2) },
    { orders: 155, quantity: 9400, price: +(price - 0.75).toFixed(2) },
  ];

  const asks = [
    { orders: 38, quantity: 1600, price: +(price + 0.05).toFixed(2) },
    { orders: 74, quantity: 3900, price: +(price + 0.15).toFixed(2) },
    { orders: 110, quantity: 5800, price: +(price + 0.30).toFixed(2) },
    { orders: 58, quantity: 2750, price: +(price + 0.50).toFixed(2) },
    { orders: 140, quantity: 8900, price: +(price + 0.75).toFixed(2) },
  ];

  const totalBidQty = bids.reduce((acc, b) => acc + b.quantity, 0);
  const totalAskQty = asks.reduce((acc, a) => acc + a.quantity, 0);

  return {
    bids,
    asks,
    totalBidQty,
    totalAskQty,
  };
};

